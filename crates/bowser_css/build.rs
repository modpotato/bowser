//! Generates `props_atom.rs`: the interned CSS property-name atom table.
//!
//! Single source of truth is the `computed_props! { NAME = "css-name", ... }`
//! invocation in `src/cascade.rs`, parsed out of the source text below. The
//! generated table lists the computed properties first, in declaration
//! order, so a [`PropertyAtom`](crate::PropertyAtom)'s index doubles as
//! the `props::*` property index; shorthand names the parser stores
//! as-is (see `is_shorthand_property` in `cascade.rs`) are appended after,
//! sorted. `PropertyAtom::lookup` is emitted as a `match` decision tree
//! over the table, mirroring `bowser_html`'s `NameAtom::lookup`.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

/// Shorthand names the parser can store on a [`Declaration`] as-is (the
/// `is_shorthand_property` set in `cascade.rs`: shorthands kept deferred
/// when their value contains `var()`). Names already in `computed_props!`
/// (`overflow`, `gap`, `grid-gap`, `columns`, `column-rule`) are deduped
/// by the generator; the rest get atoms so the cascade's deferred
/// shorthand path compares atoms instead of strings.
const SHORTHAND_NAMES: &[&str] = &[
    "background",
    "border",
    "border-block-color",
    "border-block-style",
    "border-block-width",
    "border-bottom",
    "border-color",
    "border-inline-color",
    "border-inline-style",
    "border-inline-width",
    "border-left",
    "border-radius",
    "border-right",
    "border-style",
    "border-top",
    "border-width",
    "flex",
    "font",
    "inset-block",
    "inset-inline",
    "list-style",
    "margin",
    "margin-block",
    "margin-inline",
    "overscroll-behavior",
    "padding",
    "padding-block",
    "padding-inline",
    "scroll-margin",
    "scroll-margin-block",
    "scroll-margin-inline",
    "scroll-padding",
    "scroll-padding-block",
    "scroll-padding-inline",
];

fn main() {
    println!("cargo:rerun-if-changed=src/cascade.rs");
    println!("cargo:rerun-if-changed=build.rs");

    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let cascade = fs::read_to_string(manifest.join("src/cascade.rs")).unwrap();
    let computed = parse_computed_props(&cascade);

    // Table order: computed properties in `computed_props!` declaration
    // order (index == `props::*` value), then shorthand extras sorted.
    let mut names: Vec<(String, String)> = computed;
    let computed_count = names.len();
    let mut extras: Vec<&str> = SHORTHAND_NAMES
        .iter()
        .copied()
        .filter(|n| !names.iter().any(|(_, css)| css == n))
        .collect();
    extras.sort_unstable();
    for css in extras {
        names.push((const_name(css), css.to_string()));
    }

    assert!(
        names.len() < u8::MAX as usize,
        "property atom table overflowed u8 ({} entries)",
        names.len()
    );
    let mut seen_css = std::collections::HashSet::new();
    let mut seen_const = std::collections::HashSet::new();
    for (c, css) in &names {
        assert!(seen_css.insert(css.clone()), "duplicate css name {css}");
        assert!(seen_const.insert(c.clone()), "duplicate const name {c}");
    }

    let mut out = String::new();
    out.push_str(
        "// @generated by bowser_css/build.rs -- do not hand-edit.\n\
         //\n\
         // Well-known CSS property names: the `computed_props!` list from\n\
         // `src/cascade.rs` in declaration order, then the shorthand names\n\
         // the parser stores as-is, sorted. A `PropertyAtom`'s index is its\n\
         // position here; for the leading computed-property run that index\n\
         // doubles as the `props::*` slot index.\n\n",
    );
    out.push_str("pub(crate) static PROPS: &[&str] = &[\n");
    for (_, css) in &names {
        writeln!(out, "    \"{css}\",").unwrap();
    }
    out.push_str("];\n\n");
    writeln!(
        out,
        "/// Number of leading [`PROPS`] entries that are computed properties\n\
         /// (indices match `props::*`).\n\
         pub(crate) const COMPUTED_ATOM_COUNT: usize = {computed_count};\n"
    )
    .unwrap();

    out.push_str(
        "/// Atom of a well-known CSS property name: its index in [`PROPS`].\n\
         ///\n\
         /// `Copy`, so comparing two atoms is a single `u8` comparison with\n\
         /// no allocation, no hashing, and no synchronization. For the\n\
         /// leading computed-property run the index doubles as the property\n\
         /// index (`props::*`), so the cascade hot path reads the slot\n\
         /// straight from the atom.\n\
         #[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]\n\
         pub struct PropertyAtom(u8);\n\n\
         impl PropertyAtom {\n\
         \x20   /// Not a well-known property name. The owning [`PropertyName`]\n\
         \x20   /// carries the original string on its heap sidecar; never\n\
         \x20   /// index the table with this.\n\
         \x20   pub const UNKNOWN: PropertyAtom = PropertyAtom(u8::MAX);\n\n",
    );
    for (i, (c, _)) in names.iter().enumerate() {
        writeln!(
            out,
            "    pub const {c}: PropertyAtom = PropertyAtom({i}u8);"
        )
        .unwrap();
    }
    out.push_str(
        "\n\
         \x20   /// Look up a well-known property name: exact, case-sensitive\n\
         \x20   /// (the parser lowercases non-custom names before interning).\n\
         \x20   /// Pure function -- no allocation, no hashing, no locks.\n\
         \x20   ///\n\
         \x20   /// Generated from the atom table (do not hand-edit the arms):\n\
         \x20   /// the `every_well_known_property_round_trips` test pins each\n\
         \x20   /// arm's index to the table order.\n\
         \x20   pub fn lookup(name: &str) -> Option<PropertyAtom> {\n\
         \x20       // A `match` over the table compiles to a decision tree on\n\
         \x20       // the name bytes -- much cheaper than a hash lookup per\n\
         \x20       // candidate declaration on the cascade hot path.\n\
         \x20       match name {\n",
    );
    for (i, (_, css)) in names.iter().enumerate() {
        writeln!(out, "            \"{css}\" => Some(PropertyAtom({i})),").unwrap();
    }
    out.push_str(
        "            _ => None,\n\
         \x20       }\n\
         \x20   }\n\n\
         \x20   /// The table index; for computed properties this is the\n\
         \x20   /// `props::*` slot index.\n\
         \x20   pub fn index(&self) -> u8 {\n\
         \x20       self.0\n\
         \x20   }\n\n\
         \x20   /// Whether this atom names a computed property (the leading\n\
         \x20   /// table run whose indices match `props::*`).\n\
         \x20   pub fn is_computed(&self) -> bool {\n\
         \x20       (self.0 as usize) < COMPUTED_ATOM_COUNT\n\
         \x20   }\n\n\
         \x20   /// The property name. Panics for [`PropertyAtom::UNKNOWN`],\n\
         \x20   /// which has no table entry.\n\
         \x20   pub fn as_str(&self) -> &'static str {\n\
         \x20       PROPS\n\
         \x20           .get(self.0 as usize)\n\
         \x20           .copied()\n\
         \x20           .expect(\"PropertyAtom::UNKNOWN has no table entry\")\n\
         \x20   }\n\
         }\n",
    );

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("props_atom.rs"), out).unwrap();
}

/// Parse the `computed_props! { NAME = "css-name", ... }` invocation out of
/// `cascade.rs`, returning `(CONST_NAME, css-name)` pairs in declaration
/// order.
fn parse_computed_props(cascade: &str) -> Vec<(String, String)> {
    let mut lines = cascade.lines();
    let start = lines
        .position(|l| l.trim() == "computed_props! {")
        .expect("computed_props! invocation not found in cascade.rs");
    let _ = start;
    let mut entries = Vec::new();
    for line in lines {
        let t = line.trim();
        if t == "}" {
            break;
        }
        if t.is_empty() || t.starts_with("//") || t.starts_with("#[") {
            continue;
        }
        // Entry shape: `NAME = "css-name",`
        let (name, rest) = t.split_once('=').expect("malformed computed_props entry");
        let name = name.trim();
        assert!(
            name.bytes()
                .all(|b| b.is_ascii_uppercase() || b.is_ascii_digit() || b == b'_'),
            "bad const name {name}"
        );
        let mut css = rest.trim();
        css = css.strip_suffix(',').unwrap_or(css).trim();
        assert!(
            css.len() >= 2 && css.starts_with('"') && css.ends_with('"'),
            "bad css name {css}"
        );
        entries.push((name.to_string(), css[1..css.len() - 1].to_string()));
    }
    assert!(!entries.is_empty(), "no computed_props entries parsed");
    entries
}

/// Derive a `SCREAMING_SNAKE` const name from a css property name.
fn const_name(css: &str) -> String {
    css.to_ascii_uppercase().replace('-', "_")
}
